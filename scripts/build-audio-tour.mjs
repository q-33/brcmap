#!/usr/bin/env node
// Build the Art Audio Tour: transcode the released MP3s and bake a manifest.
//
// The source files are 320 kbps stereo 44.1 kHz — about five times what spoken
// narration needs, and 273 MB in total. Re-encoded to 64 kbps mono AAC they come
// to roughly a fifth of that with no audible loss on speech, which is the
// difference between a tour that loads on playa LTE and one that doesn't.
//
// Uses macOS's built-in afconvert, so there's no ffmpeg dependency.
//
//   node scripts/build-audio-tour.mjs ["Art Audio Tour"]
//
// Writes public/audio/tour/*.m4a and lib/art/audioTour.ts. Both are committed:
// the manifest has to ship with the files it points at.
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'

const SRC = resolve(process.argv[2] ?? 'Art Audio Tour')
const OUT = resolve('public/audio/tour')
const MANIFEST = resolve('lib/art/audioTour.ts')
const BITRATE = 64000

// Tracks that are not artworks: the tour's own introduction and the theme talk.
const NON_ART = new Set([0, 87])

// Filename typos in the release. Left → what the file says, right → the artwork
// as we (and Burning Man's own listing) name it. Every one of these was checked
// by hand; nothing is renamed on a fuzzy score alone.
const TITLE_FIXES = {
  'Aetheric Ascention Tower': 'Aetheric Ascension Tower',
  'The Portal of Collective Imaginagtion': 'The Portal of Collective Imagination',
  'Apothoneum': 'Apotheneum',
  'The Council of Animals, What to do about Humans': 'The Council of Animals, What to Do about the Humans',
  'D.A.R.E. - Does Art Exist Everywhere_': 'D.A.R.E – Does Art Reside Everywhere?',
}

const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60)

if (!existsSync(SRC)) {
  console.error(`Source folder not found: ${SRC}`)
  process.exit(1)
}
mkdirSync(OUT, { recursive: true })

const tracks = []
for (const f of readdirSync(SRC).filter(f => f.toLowerCase().endsWith('.mp3'))) {
  const m = f.match(/^(\d+)\.\s*(.+)\.mp3$/)
  if (!m) {
    console.warn(`skipping unparseable name: ${f}`)
    continue
  }
  tracks.push({ num: Number(m[1]), raw: m[2].trim(), file: f })
}
tracks.sort((a, b) => a.num - b.num)

let srcBytes = 0
let outBytes = 0
for (const t of tracks) {
  // "_" stands in for characters the filesystem won't take (": " and "?")
  const title = TITLE_FIXES[t.raw] ?? t.raw.replace(/_/g, ':')
  const out = `${String(t.num).padStart(2, '0')}-${slug(title)}.m4a`
  const from = join(SRC, t.file)
  const to = join(OUT, out)
  srcBytes += statSync(from).size
  if (!existsSync(to)) {
    execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', String(BITRATE), '-c', '1', from, to])
    process.stdout.write('.')
  }
  outBytes += statSync(to).size
  t.title = title
  t.out = out
}
process.stdout.write('\n')

const mb = n => (n / 1024 / 1024).toFixed(0)
console.log(`${tracks.length} tracks · ${mb(srcBytes)} MB → ${mb(outBytes)} MB (${(srcBytes / outBytes).toFixed(1)}× smaller)`)

const art = tracks.filter(t => !NON_ART.has(t.num))
const extra = tracks.filter(t => NON_ART.has(t.num))

const lines = []
lines.push('// GENERATED by scripts/build-audio-tour.mjs — do not hand-edit.')
lines.push('//')
lines.push('// Burning Man\'s 2026 Art Audio Tour, matched to the artworks we list.')
lines.push('// Audio is served from public/audio/tour and is deliberately NOT precached by')
lines.push('// the service worker — 57 MB of narration has no business in an offline shell.')
lines.push('')
lines.push('export interface AudioTrack {')
lines.push('  /** the tour\'s own numbering, 0 = introduction */')
lines.push('  n: number')
lines.push('  /** artwork name as the tour announces it */')
lines.push('  title: string')
lines.push('  /** path under /audio/tour */')
lines.push('  file: string')
lines.push('}')
lines.push('')
lines.push('/** The tour\'s introduction and the theme talk — not tied to any artwork. */')
lines.push('export const TOUR_EXTRAS: AudioTrack[] = [')
for (const t of extra)
  lines.push(`  { n: ${t.num}, title: ${JSON.stringify(t.title)}, file: ${JSON.stringify(t.out)} },`)
lines.push(']')
lines.push('')
lines.push('/** One track per artwork, in tour order. */')
lines.push('export const TOUR_TRACKS: AudioTrack[] = [')
for (const t of art)
  lines.push(`  { n: ${t.num}, title: ${JSON.stringify(t.title)}, file: ${JSON.stringify(t.out)} },`)
lines.push(']')
lines.push('')
lines.push(`/** Normalised artwork name → track. Matching is by name because the audio ships`)
lines.push(` *  with the repo while art rows carry per-environment ids. */`)
lines.push('export function normalizeArtName(name: string): string {')
lines.push('  return name')
lines.push('    .toLowerCase()')
lines.push('    .replace(/&/g, \' and \')')
lines.push('    .replace(/[^a-z0-9]+/g, \' \')')
lines.push('    .trim()')
lines.push('}')
lines.push('')
lines.push('const BY_NAME = new Map(TOUR_TRACKS.map(t => [normalizeArtName(t.title), t]))')
lines.push('')
lines.push('/** The tour track for an artwork, or null if it has none. */')
lines.push('export function audioForArt(name: string | null | undefined): AudioTrack | null {')
lines.push('  return (name && BY_NAME.get(normalizeArtName(name))) || null')
lines.push('}')
lines.push('')
lines.push('/** Public URL for a track. */')
lines.push('export function audioUrl(t: AudioTrack): string {')
lines.push('  return `/audio/tour/${t.file}`')
lines.push('}')

mkdirSync(resolve('lib/art'), { recursive: true })
writeFileSync(MANIFEST, `${lines.join('\n')}\n`)
console.log(`wrote ${basename(MANIFEST)} — ${art.length} artwork tracks, ${extra.length} extras`)
